const userProducts = {};

function pick(arr, seed) {
  return arr[seed % arr.length];
}

const reviews = [];
let seed = 1337;
for (let i = 0; i < 317; i++) {
  seed = (seed * 1103515245 + 12345) & 0x7fffffff;
  const name = names[seed % names.length];
  const city = cities[(seed >> 3) % cities.length];
  const prodKeys = Object.keys(products);
  const product = prodKeys[(seed >> 5) % prodKeys.length];
  const plan = products[product][(seed >> 7) % products[product].length];
  const tpl = templates[i % templates.length];
  const text = tpl.text.replace(/{product}/g, product).replace(/{plan}/g, plan);
  const daysAgo = (seed % 365) + 1;
  const d = new Date();
  d.setDate(d.getDate() - daysAgo);
  const date = d.toISOString().slice(0, 10);
  reviews.push({
    id: i + 1,
    name,
    city,
    product,
    plan,
    rating: tpl.rating,
    text,
    date,
    verified: true,
  });
}

// Compute summary
const avg = (reviews.reduce((s, r) => s + r.rating, 0) / reviews.length).toFixed(2);
const dist = { 5: 0, 4: 0, 3: 0, 2: 0, 1: 0 };
reviews.forEach((r) => (dist[r.rating]++));

const out = { total: reviews.length, avg: Number(avg), distribution: dist, reviews };
const outPath = path.join(__dirname, '..', 'public', 'reviews.json');
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, JSON.stringify(out, null, 2), 'utf8');
console.log(`Generated ${reviews.length} reviews, avg ${avg}`);